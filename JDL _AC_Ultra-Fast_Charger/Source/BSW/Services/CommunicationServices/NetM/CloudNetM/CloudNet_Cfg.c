char *CloudNet_Strdup(const char *s)
{
    if (s == NULL)
    {
        return NULL;
    }
    size_t len = strlen(s) + 1;
    char *new_str = (char *)CLOUDM_MALLOC(len);
    if (new_str != NULL)
    {
        memcpy(new_str, s, len);
    }
    return new_str;
}
