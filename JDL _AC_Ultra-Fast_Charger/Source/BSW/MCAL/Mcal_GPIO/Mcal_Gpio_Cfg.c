/* 初始化GPIO模块 */
void Mcal_Gpio_Init(void)
{
    MX_GPIO_Init();
}

/* 设置GPIO引脚输出高电平 */
void Mcal_Gpio_SetPin(GPIO_TypeDef  *GPIOx, uint32_t pin)
{
    HAL_GPIO_WritePin(GPIOx, pin, GPIO_PIN_SET);
}

/* 设置GPIO引脚输出低电平 */
void Mcal_Gpio_ResetPin(GPIO_TypeDef  *GPIOx, uint32_t pin)
{
    HAL_GPIO_WritePin(GPIOx, pin, GPIO_PIN_RESET);
}

Mcal_GPIO_PinState Mcal_Gpio_ReadPinStatus(GPIO_TypeDef  *GPIOx, uint32_t pin)
{
    if (HAL_GPIO_ReadPin(GPIOx, pin) == GPIO_PIN_SET)
    {
        return MCAL_GPIO_PIN_SET;  // 引脚状态为高
    }
    else
    {
        return MCAL_GPIO_PIN_RESET; // 引脚状态为低
    }
}

